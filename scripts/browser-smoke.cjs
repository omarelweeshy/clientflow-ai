/* Repeatable real-browser checks against the running DEMO stack only. */
const {chromium} = require('../frontend/node_modules/playwright');
const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const origin = process.env.CLIENTFLOW_URL || 'http://localhost:3010';

(async () => {
  const browser = await chromium.launch({headless:true, ...(process.env.BROWSER_CHANNEL ? {channel:process.env.BROWSER_CHANNEL} : {})});
  const context = await browser.newContext({viewport:{width:1440,height:1000}, reducedMotion:'reduce'});
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const screenshots = path.join(root, 'docs', 'screenshots');
  await fs.mkdir(screenshots, {recursive:true});
  async function capture(name, heading) {
    if (heading) await page.getByRole('heading', {name:heading, exact:true}).waitFor();
    await page.locator('.loading').waitFor({state:'detached'});
    await page.screenshot({path:path.join(screenshots,name),fullPage:true});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `Page overflow: ${name}`);
  }
  await page.goto(origin+'/login');
  await page.getByLabel('Administrator password').fill((await fs.readFile(path.join(root,'local-secrets','admin-password.txt'),'utf8')).trim());
  await page.getByRole('button',{name:'Open workspace',exact:true}).click();
  await page.waitForURL('**/dashboard');
  await capture('overview-desktop.png','Keep good work moving.');
  await page.getByRole('link',{name:'Lead pipeline',exact:true}).click();
  await page.getByRole('textbox',{name:'Search leads'}).fill('Nadia');
  await page.getByRole('link',{name:'Open Nadia Farouk',exact:true}).click();
  await capture('lead-desktop.png','Automation timeline');
  assert.ok(await page.getByText('Qualification calculated',{exact:true}).count());
  await page.getByRole('link',{name:/Approval queue/}).first().click();
  await capture('approvals-desktop.png','Approval queue');
  await page.getByRole('link',{name:'Automation runs',exact:true}).click();
  await page.getByLabel('Only unresolved failures').check();
  await capture('failures-desktop.png','Automation ledger');
  // Failure fixtures may already be resolved on a reused installation.
  await page.getByRole('link',{name:'Settings',exact:true}).click();
  await capture('settings-desktop.png','Qualification rules');
  await page.goto(origin+'/intake');
  await capture('intake-desktop.png','Tell us about your project');
  await page.getByLabel('Full name').fill('Browser Demo Prospect');
  const email = `browser.${Date.now()}@example.com`;
  await page.getByRole('textbox',{name:/^Email/}).fill(email);
  await page.getByLabel('Company',{exact:true}).fill('Fictional Browser Studio');
  await page.getByLabel('What can we help with?').selectOption('Workflow integration');
  await page.getByLabel('Describe your project').fill('We need to connect our enquiry form to an internal CRM and prepare responses for human approval.');
  await page.getByLabel('Budget range').selectOption('2000-5000');
  const deadline = new Date();
  deadline.setDate(deadline.getDate() + 45);
  await page.getByLabel('Desired deadline').fill(deadline.toISOString().slice(0,10));
  await page.getByRole('checkbox').check();
  await page.getByRole('button',{name:'Send project enquiry'}).click();
  await page.getByRole('heading',{name:'It’s in good hands.'}).waitFor();
  await page.goto(origin+'/dashboard/pipeline');
  await page.getByRole('textbox',{name:'Search leads'}).fill(email);
  await page.getByRole('link',{name:'Open Browser Demo Prospect',exact:true}).click();
  await page.getByRole('heading',{name:'Automation timeline'}).waitFor();
  await page.getByRole('button',{name:'Approve',exact:true}).click();
  await page.getByRole('button',{name:'Send approved',exact:true}).click();
  await page.getByText('Email sent',{exact:true}).waitFor();
  await page.getByLabel('Reply received').check();
  await page.getByText('Followup cancelled',{exact:true}).first().waitFor();
  await page.setViewportSize({width:390,height:844});
  await capture('lead-mobile.png','Automation timeline');
  await page.goto(origin+'/dashboard');
  await capture('overview-mobile.png','Keep good work moving.');
  await page.getByRole('button',{name:'Open navigation'}).click();
  await page.getByRole('link',{name:/Approval queue/}).first().click();
  await capture('approvals-mobile.png','Approval queue');
  await page.goto(origin+'/dashboard/runs');
  await capture('failures-mobile.png','Automation ledger');
  await page.goto(origin+'/intake');
  await capture('intake-mobile.png','Tell us about your project');
  assert.deepEqual(errors, [], 'Browser runtime errors');
  await browser.close();
  console.log('PASS: desktop/mobile screens, form submission, approval, mock send, reply cancellation, no page overflow or runtime errors.');
})().catch(error => {console.error(error);process.exit(1);});
